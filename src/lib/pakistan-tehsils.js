// Grouped by Alphabet Letter (A-Z)
export const TEHSILS_BY_LETTER = (() => {
  const groups = {};
  for (let i = 65; i <= 90; i++) {
    const letter = String.fromCharCode(i);
    groups[letter] = [];
  }
  ALL_PAKISTAN_TEHSILS.forEach(t => {
    const firstChar = t.name.charAt(0).toUpperCase();
    if (groups[firstChar]) {
      groups[firstChar].push(t);
    } else {
      if (!groups["#"]) groups["#"] = [];
      groups["#"].push(t);
    }
  });
  return groups;
})();

export const ALPHABET_INDEX = Object.keys(TEHSILS_BY_LETTER).filter(
  letter => TEHSILS_BY_LETTER[letter].length > 0
);

/**
 * Fast search across Tehsil name, District, Division, and Province
 */
export function searchTehsils(query) {
  if (!query || !query.trim()) return ALL_PAKISTAN_TEHSILS;
  const q = query.toLowerCase().trim();
  return ALL_PAKISTAN_TEHSILS.filter(t => 
    t.name.toLowerCase().includes(q) ||
    t.district.toLowerCase().includes(q) ||
    t.division.toLowerCase().includes(q) ||
    t.province.toLowerCase().includes(q)
  );
}

/**
 * Haversine formula to compute distance in km between two GPS coordinates
 */
export function haversineDistance(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

/**
 * Finds the nearest Tehsil given latitude and longitude
 */
export function findNearestTehsil(userLat, userLng) {
  if (!userLat || !userLng) return null;
  let nearest = null;
  let minDistance = Infinity;

  for (const t of ALL_PAKISTAN_TEHSILS) {
    const dist = haversineDistance(userLat, userLng, t.lat, t.lng);
    if (dist < minDistance) {
      minDistance = dist;
      nearest = {
        ...t,
        distanceKm: Math.round(dist * 10) / 10
      };
    }
  }
  return nearest;
}

/**
 * Formats a clean, readable display label for frontend display
 * e.g. "Mehria Town, Attock City" or "DHA Phase 5, Lahore"
 */
export function formatLocationDisplay(area, tehsil, district) {
  const cleanArea = area ? area.trim() : "";
  const cleanTehsil = tehsil ? tehsil.trim() : "";
  const cleanDistrict = district ? district.trim() : "";

  const cityBase = cleanTehsil || cleanDistrict;
  if (!cityBase) return cleanArea || "Pakistan";

  // Append "City" if not already in the name and not a compound like "Model Town"
  let formattedCity = cityBase;
  if (
    !formattedCity.toLowerCase().includes("city") &&
    !formattedCity.toLowerCase().includes("town") &&
    !formattedCity.toLowerCase().includes("cantonment") &&
    !formattedCity.toLowerCase().includes("saddar")
  ) {
    formattedCity = `${formattedCity} City`;
  }

  if (cleanArea) {
    return `${cleanArea}, ${formattedCity}`;
  }
  return formattedCity;
}
